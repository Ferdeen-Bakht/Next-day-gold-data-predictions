"""### Genetic Algorithm for `SAG_LSTM` Hyperparameter Optimization

To find optimal hyperparameters for the `SAG_LSTM` model, we'll employ a basic Genetic Algorithm (GA). The GA will iteratively evolve a population of hyperparameter sets (individuals) and evaluate their performance using the `SAG_LSTM` model trained on the validation set. The goal is to minimize the RMSE on the validation set.

**Hyperparameters to Optimize:**
-   `hidden_size`: Controls the dimensionality of the internal state of the LSTM and attention layers.
-   `learning_rate`: Determines the step size at each iteration while moving toward a minimum of the loss function.
-   `epochs`: The number of complete passes through the entire training dataset.
"""

# Define the fitness function for the genetic algorithm
def fitness_function(
    individual,
    input_size,
    output_size,
    train_loader,
    val_loader,
    target_scaler,
    device
):
    hidden_size, learning_rate, epochs = individual
    epochs = int(epochs) # Ensure epochs is an integer

    model = SAG_LSTM(
        input_size=input_size,
        hidden_size=int(hidden_size), # hidden_size must be int
        output_size=output_size
    ).to(device)

    # Train the model and get validation loss
    # Suppress verbose output during GA fitness evaluation
    original_print = __builtins__.print
    __builtins__.print = lambda *args, **kwargs: None

    try:
        _, history = train_model(
            model,
            train_loader,
            val_loader,
            epochs=epochs,
            learning_rate=learning_rate,
            target_scaler=target_scaler
        )
    finally:
        __builtins__.print = original_print # Restore print function

    # We want to minimize validation loss (e.g., RMSE)
    # The train_model function returns val_rmse in its history.
    # We can use the last validation RMSE as the fitness score.
    # If the history is empty or an error occurred, return a very high value.
    if not history["val_rmse"]:
        return float('inf')
    return history["val_rmse"][-1] # Minimize RMSE

# Genetic Algorithm parameters
POPULATION_SIZE = 5
GENERATIONS = 5
MUTATION_RATE = 0.15
CROSSOVER_RATE = 0.7

# Hyperparameter ranges (for SAG_LSTM)
HIDDEN_SIZE_RANGE = [64, 128, 256] # min and max
LEARNING_RATE_RANGE = [0.0001,0.01]
EPOCHS_RANGE = [5, 10, 15] # min and max

def create_individual():
    return [
        np.random.randint(HIDDEN_SIZE_RANGE[0], HIDDEN_SIZE_RANGE[1] + 1), # hidden_size
        np.random.uniform(LEARNING_RATE_RANGE[0], LEARNING_RATE_RANGE[1]), # learning_rate
        np.random.randint(EPOCHS_RANGE[0], EPOCHS_RANGE[1] + 1) # epochs
    ]

def mutate_individual(individual):
    mutated_individual = list(individual) # Create a mutable copy
    if np.random.rand() < MUTATION_RATE:
        idx = np.random.randint(len(mutated_individual))
        if idx == 0: # hidden_size
            mutated_individual[idx] = np.random.randint(HIDDEN_SIZE_RANGE[0], HIDDEN_SIZE_RANGE[1] + 1)
        elif idx == 1: # learning_rate
            mutated_individual[idx] = np.random.uniform(LEARNING_RATE_RANGE[0], LEARNING_RATE_RANGE[1])
        elif idx == 2: # epochs
            mutated_individual[idx] = np.random.randint(EPOCHS_RANGE[0], EPOCHS_RANGE[1] + 1)
    return mutated_individual

def crossover_individuals(parent1, parent2):
    if np.random.rand() < CROSSOVER_RATE:
        crossover_point = np.random.randint(1, len(parent1)) # Crossover point can be 1 or 2
        child1 = parent1[:crossover_point] + parent2[crossover_point:]
        child2 = parent2[:crossover_point] + parent1[crossover_point:]
        return child1, child2
    return list(parent1), list(parent2) # Return copies to avoid modifying originals

def run_genetic_algorithm(
    population_size,
    generations,
    input_size,
    output_size,
    train_loader,
    val_loader,
    target_scaler,
    device
):
    population = [create_individual() for _ in range(population_size)]
    best_individual = None
    best_fitness = float('inf')

    for generation in range(generations):
        print(f"--- Genetic Algorithm: Generation {generation + 1}/{generations} ---")
        fitnesses = [
            fitness_function(
                ind,
                input_size,
                output_size,
                train_loader,
                val_loader,
                target_scaler,
                device
            ) for ind in population
        ]

        for i, fitness in enumerate(fitnesses):
            if fitness < best_fitness:
                best_fitness = fitness
                best_individual = population[i]

        print(f"  Best fitness (RMSE) in generation {generation + 1}: {best_fitness:.4f}")
        print(f"  Current Best Params: hidden_size={int(best_individual[0])}, lr={best_individual[1]:.5f}, epochs={int(best_individual[2])})")

        # Selection (simple elitism + roulette wheel/random for rest)
        sorted_population_with_fitness = sorted(zip(fitnesses, population), key=lambda pair: pair[0])
        new_population = [list(ind) for _, ind in sorted_population_with_fitness[:population_size // 2]] # Elitism, ensure mutable copies

        # Fill the rest of the population with crossover and mutation
        while len(new_population) < population_size:
            # Select parents from the 'fitter' half (or all, depending on strategy)
            parent1_idx = np.random.randint(len(sorted_population_with_fitness) // 2)
            parent2_idx = np.random.randint(len(sorted_population_with_fitness) // 2)
            parent1 = sorted_population_with_fitness[parent1_idx][1]
            parent2 = sorted_population_with_fitness[parent2_idx][1]

            child1, child2 = crossover_individuals(parent1, parent2)
            new_population.append(mutate_individual(child1))
            if len(new_population) < population_size:
                new_population.append(mutate_individual(child2))

        population = new_population

    return best_individual

